// node tools/record_zones.js : loads the dev build (python -m http.server 8123 in the repo root) in headless Chromium
// and records which texture files are first requested while the district sites are being built (window.__texPhase =
// 'district' in main.js) versus the rest of the game. Writes tools/texture_zones.json { district: [names...] }, which
// tools/pack_textures.py uses to put district-only textures into packs that stream in after the game starts.
const { chromium } = require('playwright'); const fs = require('fs'); const path = require('path');
(async () => {
  const b = await chromium.launch(); const p = await b.newPage({ viewport: { width: 800, height: 500 } });
  await p.addInitScript(() => { window.__texLog = {}; window.__texPhase = 'core';
    const d = Object.getOwnPropertyDescriptor(HTMLImageElement.prototype, 'src');
    Object.defineProperty(HTMLImageElement.prototype, 'src', { configurable: true, get() { return d.get.call(this); }, set(v) { const m = String(v).match(/assets\/textures\/([^?#]+)/); if (m && !(m[1] in window.__texLog)) window.__texLog[m[1]] = window.__texPhase; d.set.call(this, v); } }); });
  await p.goto('http://localhost:8123/', { waitUntil: 'commit', timeout: 120000 });
  await p.waitForFunction(() => window.__scene, null, { timeout: 600000, polling: 1000 });
  const log = await p.evaluate(() => window.__texLog);
  const district = Object.keys(log).filter((k) => log[k] === 'district').sort(), core = Object.keys(log).filter((k) => log[k] !== 'district');
  fs.writeFileSync(path.join(__dirname, 'texture_zones.json'), JSON.stringify({ note: 'generated by tools/record_zones.js; files in neither list are unused and go to the district packs', core: core.sort(), district }, null, 1));
  console.log('core', core.length, 'district', district.length);
  await b.close();
})();
